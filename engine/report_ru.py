"""俄语版集体评价报告渲染层 (report_ru.py)
=========================================
表单版界面切到 Русский 时，报告正文也必须是俄文。

设计原则（不改动中文路径，避免回归）：
  * 报告骨架、表头、结论、法律提示 —— 本模块用俄文直接撰写；
  * 指标名 —— 取知识库里的权威俄文名（data/ru_standards.json 的 name_ru
    与 data/cn_indicator_ru.json 的映射），不自行杜撰；
  * 指标判定行 —— 由结构化数据（requirement / product_value / clause / verdict）
    在俄语里**重新组装**，而不是翻译中文 detail 串，避免语序错乱；
  * §三 尺寸与工艺对比表 —— 复用 llm_report._detail_table 的判定逻辑（保证与 §四/§五
    同口径），只把单元格文案按词条表译成俄文；
  * 用户自己填的自由文本（型号、备注）与标准编号、牌号 —— 原样保留。

入口：report_ru(product, result) -> str
"""
