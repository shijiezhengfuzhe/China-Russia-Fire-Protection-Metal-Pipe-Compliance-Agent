def _side_ru(L, title, key, skipped_key, r):
    L.append(f"## {title}")
    if not r.get(key):
        L.append("(применимые стандарты не найдены)")
    for s in r[key]:
        sid = s.get("standard") or ""
        nm = std_ru(sid) or (s.get("name_zh") or "")
        L.append(f"### {sid}　{nm}")
        nas = []
        for it in s["items"]:
            iid = it.get("indicator_id") or ""
            tail = str(iid).split(".")[-1].upper()
            opt = " (опционально / по согласованию)" if ("NDT" in str(iid).upper() or tail == "NDT") else ""
            name = ind_ru(iid, it.get("indicator_zh") or "")
            unit = unit_ru(it.get("unit"))
            val = MISSING if it.get("product_value") is None else it.get("product_value")
            if it["verdict"] == "na":
                nas.append(it)
                continue
            verdict = "ПРОЙДЕНО" if it["verdict"] == "pass" else "НЕ ПРОЙДЕНО"
            L.append(f"- {_flag(it['verdict'])} {name}{opt} ({iid}) "
                     f"значение={val} {unit} → **{verdict}** | пункт: {tr(it.get('clause') or '—')} "
                     f"| требование: {req_ru(it.get('requirement'))}")
        if nas:
            L.append(f":::na  ◻️ Не оценено / требует решения: {len(nas)} (развернуть, чтобы увидеть причину и ссылку)")
            for it in nas:
                iid = it.get("indicator_id") or ""
                tail = str(iid).split(".")[-1].upper()
                opt = " (опционально)" if ("NDT" in str(iid).upper() or tail == "NDT") else ""
                name = ind_ru(iid, it.get("indicator_zh") or "")
                unit = unit_ru(it.get("unit"))
                val = MISSING if it.get("product_value") is None else it.get("product_value")
                kind, reason, hint = na_reason_ru(it)
                L.append(f"   • **{name}**{opt} ({iid})　значение={val} {unit}　| пункт: {tr(it.get('clause') or '—')}")
                L.append(f"     ✋ {kind}: {reason}")
                L.append(f"     📖 требование: {req_ru(it.get('requirement'))}")
                L.append(f"     💡 рекомендация: {hint}")
            L.append(":::")
        for sid2 in r.get(skipped_key, []):
            L.append(f"- ⚠ в базе знаний отсутствует стандарт: {sid2}")
        L.append("")


