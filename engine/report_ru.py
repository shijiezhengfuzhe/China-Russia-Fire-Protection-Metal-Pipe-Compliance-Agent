def std_ru(std_id, name_zh=""):
    """标准俄文名：ГОСТ/СП 取知识库 name_ru；GB/T 取对照表；否则回退。"""
    sid = str(std_id or "").strip()
    up = sid.upper()
    for k, v in _load()["std"].items():
        if k == up or k.startswith(up) or up.startswith(k):
            return v
    return CN_STD_RU.get(up) or SP_RU.get(up) or ""


