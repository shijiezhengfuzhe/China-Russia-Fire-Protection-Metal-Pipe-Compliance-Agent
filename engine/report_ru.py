def req_ru(req):
    """把 requirement 结构渲染成俄文要求串。"""
    if not isinstance(req, dict):
        return "—"
    if "min" in req and "max" in req:
        return f"{req['min']} … {req['max']}"
    if "min" in req:
        return f"≥ {req['min']}"
    if "max" in req:
        return f"≤ {req['max']}"
    if "range" in req:
        r = req["range"]
        return f"{r[0]} … {r[1]}"
    if "set" in req or "series" in req:
        vals = req.get("set") or req.get("series") or []
        vals = tr_list(vals)
        head = ", ".join(str(x) for x in vals[:12])
        more = ", …" if len(vals) > 12 else ""
        return f"значение из ряда: {head}{more}"
    if "bool" in req:
        return f"логическое требование: {req['bool']}"
    if "table" in req:
        return f"табличное требование ({len(req.get('table') or [])} строк)"
    if "map" in req:
        return "перечисление групп (А/Б/В)"
    if "desc" in req:
        return "описательное требование (текстом)"
    if "spec" in req:
        return "специальное требование"
    return "—"


