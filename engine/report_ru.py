_CACHE = {}


def _load():
    if _CACHE:
        return _CACHE
    ind, std = {}, {}
    try:
        ru = json.loads((DATA_DIR / "ru_standards.json").read_text(encoding="utf-8"))
    except Exception:
        ru = {"standards": []}
    for s in ru.get("standards", []):
        sid = str(s.get("id") or "")
        if sid and s.get("name_ru"):
            std[sid.upper()] = s["name_ru"]
        for it in s.get("indicators") or []:
            iid = str(it.get("id") or "")
            if iid and it.get("name_ru"):
                ind[iid.upper()] = it["name_ru"]
    try:
        cnmap = json.loads((DATA_DIR / "cn_indicator_ru.json").read_text(encoding="utf-8"))["map"]
    except Exception:
        cnmap = {}
    for k, v in cnmap.items():
        ind.setdefault(str(k).upper(), v)      # 俄标权威名优先
        ind[str(k).upper()] = v if v else ind.get(str(k).upper())
    for k, v in cnmap.items():
        ind[str(k).upper()] = v
    _CACHE["ind"] = ind
    _CACHE["std"] = std
    return _CACHE


def ind_ru(ind_id, fallback=""):
    """指标俄文名：知识库优先，其次按后缀兜底。"""
    key = str(ind_id or "").upper()
    m = _load()["ind"].get(key)
    if m:
        return m
    tail = key.split(".")[-1]
    return TAIL_RU.get(tail, fallback or (ind_id or ""))


