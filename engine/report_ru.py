def tr(text):
    """把 §三 单元格里的中文词条译成俄文，并清掉残留中文括注。"""
    if text is None:
        return text
    s = str(text)
    for zh, ru in _SORTED:
        if zh in s:
            s = s.replace(zh, ru)
    s = s.replace("§四", "§4").replace("§五", "§5").replace("§三", "§3")
    s = s.replace("中国", "КНР").replace("俄罗斯", "РФ")
    # 残留中文括注（如 "обязательная сертификация(强制认证)"）整体删除
    s = re.sub(r"[（(][^（()）]*[\u4e00-\u9fff][^（()）]*[）)]", "", s)
    s = s.replace("（", " (").replace("）", ")")
    s = unit_ru(s)                       # 单位俄文化
    s = re.sub(r"([^\s(×−±])\(", r"\1 (", s)    # 括号前补空格（"×(" 等数学符号除外）
    s = re.sub(r"\s{2,}", " ", s)
    return s.strip()


_UNIT_PAT = [
    (r"\bMPa\b", "МПа"), (r"\bmm/m\b", "мм/м"), (r"\bg/m²\b", "г/м²"),
    (r"\bkg/m\b", "кг/м"), (r"\bμm\b", "мкм"), (r"\bmm\b", "мм"),
    (r"\bkg\b", "кг"),
]
_UNIT_WORD = {"级": "класс", "-": "", "": ""}


def unit_ru(u):
    """单位俄文化：mm→мм、MPa→МПа、级→класс、'-'→空。"""
    s = "" if u is None else str(u).strip()
    if s in _UNIT_WORD:
        return _UNIT_WORD[s]
    for pat, rep in _UNIT_PAT:
        s = re.sub(pat, rep, s)
    return s


def tr_list(vals):
    """把知识库里的中文枚举值译成俄文。"""
    out = []
    for v in vals:
        s = str(v)
        out.append(VOCAB.get(s) or tr(s))
    return out


_SORTED = sorted(PHRASES + [(k, v) for k, v in VOCAB.items() if len(k) >= 3],
                 key=lambda kv: -len(kv[0]))


